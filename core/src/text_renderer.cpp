// ─── Glyph lookup ───────────────────────────────────────────────
const uint8_t* TextRenderer::getGlyph(char c) {
    if (c < 32 || c > 126) {
        // Fallback: solid rectangle for unprintable characters
        static const uint8_t fallback[8] = {
            0xFF,0x81,0x81,0x81,0x81,0x81,0x81,0xFF
        };
        return fallback;
    }
    return FONT_DATA[c - 32];
}

// ─── Measure text ───────────────────────────────────────────────
void TextRenderer::measureText(const std::string& text, double scale,
                               int& outWidth, int& outHeight) {
    int sc = std::max(1, static_cast<int>(std::round(scale)));
    outWidth  = static_cast<int>(text.size()) * GLYPH_W * sc;
    outHeight = GLYPH_H * sc;
}

// ─── fitFontSize ────────────────────────────────────────────────
// Binary-search the largest integer scale such that the rendered
// text fits within boxWidth × boxHeight.
double TextRenderer::fitFontSize(
    const std::string& text,
    double boxWidth,
    double boxHeight,
    double minScale,
    double maxScale)
{
    double bestScale = minScale;
    for (double s = maxScale; s >= minScale; s -= 0.5) {
        int w, h;
        measureText(text, s, w, h);
        if (w <= boxWidth && h <= boxHeight) {
            bestScale = s;
            break;
        }
    }
    return bestScale;
}

// ─── Render text into a flat (non-perspective) RGBA buffer ──────
void TextRenderer::renderFlat(
    const std::string& text,
    const Color& color,
    double scale,
    FrameBuffer& buffer)
{
    int w, h;
    measureText(text, scale, w, h);
    int sc = std::max(1, static_cast<int>(std::round(scale)));

    buffer.width  = w;
    buffer.height = h;
    buffer.stride = w * 4;
    buffer.data.assign(w * h * 4, 0); // transparent black

    for (size_t ci = 0; ci < text.size(); ++ci) {
        const uint8_t* glyph = getGlyph(text[ci]);
        int baseX = static_cast<int>(ci) * GLYPH_W * sc;

        for (int gy = 0; gy < GLYPH_H; ++gy) {
            uint8_t row = glyph[gy];
            for (int gx = 0; gx < GLYPH_W; ++gx) {
                // MSB = leftmost pixel
                if (row & (0x80 >> gx)) {
                    // Fill a sc×sc block
                    for (int sy = 0; sy < sc; ++sy) {
                        for (int sx = 0; sx < sc; ++sx) {
                            int px = baseX + gx * sc + sx;
                            int py = gy * sc + sy;
                            if (px >= 0 && px < w && py >= 0 && py < h) {
                                int idx = py * buffer.stride + px * 4;
                                buffer.data[idx]     = color.red;
                                buffer.data[idx + 1] = color.green;
                                buffer.data[idx + 2] = color.blue;
                                buffer.data[idx + 3] = 255;
                            }
                        }
                    }
                }
            }
        }
    }
}

// ─── renderText — flat render then perspective warp ─────────────
void TextRenderer::renderText(
    FrameBuffer& frame,
    const std::string& text,
    const Quad& region,
    const StyleInfo& style) const
{
    if (text.empty()) return;

    // Compute the bounding box to estimate how much space we have
    BoundingBox bbox(region);
    double scale = fitFontSize(text, bbox.width, bbox.height);

    // Render into a flat off-screen buffer
    FrameBuffer textBuf;
    renderFlat(text, style.foreground, scale, textBuf);

    if (textBuf.width == 0 || textBuf.height == 0) return;

    // Warp the flat text buffer into the perspective quad on the frame
    Homography::warpInto(textBuf, frame, region);
}

